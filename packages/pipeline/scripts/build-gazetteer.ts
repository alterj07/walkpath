/**
 * Rebuilds src/data/us-cities.ts from the GeoNames cities5000 dump.
 *
 *   node packages/pipeline/scripts/build-gazetteer.ts [path/to/cities5000.zip|cities5000.txt]
 *
 * With no argument the zip is downloaded from https://download.geonames.org/export/dump/cities5000.zip.
 * Keeps US places with population >= 10,000: name, state code, population.
 * GeoNames data is CC BY 4.0 (https://www.geonames.org/).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateRawSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SOURCE_URL = 'https://download.geonames.org/export/dump/cities5000.zip';
const MIN_POPULATION = 10_000;

/** Minimal reader for a single-entry zip (GeoNames dumps are one text file each). */
function unzipSingleEntry(zip: Buffer): Buffer {
  let eocd = -1;
  for (let i = zip.length - 22; i >= Math.max(0, zip.length - 65_557); i--) {
    if (zip.readUInt32LE(i) === 0x06054b50) {
      eocd = i;
      break;
    }
  }
  if (eocd < 0) throw new Error('not a zip file');
  const centralOffset = zip.readUInt32LE(eocd + 16);
  if (zip.readUInt32LE(centralOffset) !== 0x02014b50) throw new Error('bad central directory');
  const method = zip.readUInt16LE(centralOffset + 10);
  const compressedSize = zip.readUInt32LE(centralOffset + 20);
  const localOffset = zip.readUInt32LE(centralOffset + 42);
  if (zip.readUInt32LE(localOffset) !== 0x04034b50) throw new Error('bad local header');
  const nameLen = zip.readUInt16LE(localOffset + 26);
  const extraLen = zip.readUInt16LE(localOffset + 28);
  const start = localOffset + 30 + nameLen + extraLen;
  const data = zip.subarray(start, start + compressedSize);
  if (method === 0) return Buffer.from(data);
  if (method === 8) return inflateRawSync(data);
  throw new Error(`unsupported zip method ${method}`);
}

async function loadText(arg: string | undefined): Promise<string> {
  if (arg && arg.endsWith('.txt')) return readFileSync(arg, 'utf8');
  let zip: Buffer;
  if (arg) {
    zip = readFileSync(arg);
  } else {
    const res = await fetch(SOURCE_URL);
    if (!res.ok) throw new Error(`download failed: ${res.status}`);
    zip = Buffer.from(await res.arrayBuffer());
  }
  return unzipSingleEntry(zip).toString('utf8');
}

const text = await loadText(process.argv[2]);
const rows: Array<[string, string, number]> = [];
for (const line of text.split('\n')) {
  const f = line.split('\t');
  // GeoNames columns: 1 name, 8 country code, 10 admin1 code, 14 population.
  if (f[8] !== 'US') continue;
  const population = Number(f[14]);
  const name = f[1] ?? '';
  const state = f[10] ?? '';
  if (!(population >= MIN_POPULATION) || !name || !/^[A-Z]{2}$/.test(state)) continue;
  if (name.includes('|')) continue;
  rows.push([name, state, population]);
}
rows.sort((a, b) => b[2] - a[2] || a[0].localeCompare(b[0]));

const out = `// Generated by scripts/build-gazetteer.ts. Do not edit by hand.
// Contains data from GeoNames (geonames.org), CC BY 4.0. US places with population >= ${MIN_POPULATION}.
// One place per line: name|state|population.
export const US_CITIES_RAW = \`
${rows.map((r) => r.join('|')).join('\n')}
\`;
`;
const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'src', 'data', 'us-cities.ts');
writeFileSync(target, out);
console.log(`wrote ${rows.length} cities (${out.length} bytes) to ${target}`);
